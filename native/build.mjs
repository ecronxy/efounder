// Builds native/ton-vanity-native (needs a C compiler and OpenSSL headers).
// The CLI picks it up automatically; without it the pure-JS workers are used.
import { execFileSync, spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { WORDLIST } from '../lib/wordlist.mjs';

const FALLBACK = 'eFounder still works without it: the CLI falls back to the pure-JS engine (about 4x slower).';

function giveUp(msg) {
  console.error(`\nnative core not built: ${msg}\n${FALLBACK}\n`);
  process.exit(1);
}

// the core uses Linux/macOS APIs (getrandom, pthreads, unistd)
if (process.platform === 'win32') {
  giveUp('Windows is not supported yet. To get the fast core, run eFounder inside WSL.');
}

const dir = path.dirname(fileURLToPath(import.meta.url));
fs.writeFileSync(
  path.join(dir, 'wordlist.h'),
  `// generated by build.mjs from lib/wordlist.mjs\nstatic const char *const WORDLIST[2048] = {${WORDLIST.map((w) => `"${w}"`).join(',')}};\n`
);

const cc = [process.env.CC, 'cc', 'gcc', 'clang'].find(
  (c) => c && !spawnSync(c, ['--version'], { stdio: 'ignore' }).error
);
if (!cc) giveUp('no C compiler found (tried cc, gcc, clang). Install gcc or clang, or set CC.');

const args = ['-O3', '-march=native', '-pthread', '-Wall', '-o', 'ton-vanity-native', 'vanity.c', '-lcrypto'];
console.log(cc, args.join(' '));
try {
  execFileSync(cc, args, { cwd: dir, stdio: 'inherit' });
} catch {
  giveUp('compilation failed (see the error above). Usually missing OpenSSL headers: install libssl-dev / openssl-devel / openssl.');
}
console.log('built native/ton-vanity-native');
